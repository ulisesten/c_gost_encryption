/** @def GOST_GAMMA_C1
 *  @brief Additive constant C1 of the gamma counter (reference behaviour).
 */
#define GOST_GAMMA_C1 UINT32_C(0x1010101)
/** @def GOST_GAMMA_C2
 *  @brief Additive constant C2 of the gamma counter (reference behaviour).
 */
#define GOST_GAMMA_C2 UINT32_C(0x1010104)

/** @return x rotated left by n bits. */
static uint32_t rotl32(uint32_t x, unsigned n)
{
    return (x << n) | (x >> (32U - n));
}

/** @return Block bytes decoded as two little-endian 32-bit words. */
static void words_from_block(const uint8_t *block, uint32_t words[2])
{
    words[0] = (uint32_t)block[0] | ((uint32_t)block[1] << 8U) | ((uint32_t)block[2] << 16U) |
               ((uint32_t)block[3] << 24U);
    words[1] = (uint32_t)block[4] | ((uint32_t)block[5] << 8U) | ((uint32_t)block[6] << 16U) |
               ((uint32_t)block[7] << 24U);
}

/** @brief Encode two 32-bit words as little-endian block bytes. */
static void words_to_block(const uint32_t words[2], uint8_t *block)
{
    for (unsigned i = 0; i < 2; i++) {
        block[4U * i] = (uint8_t)words[i];
        block[4U * i + 1U] = (uint8_t)(words[i] >> 8U);
        block[4U * i + 2U] = (uint8_t)(words[i] >> 16U);
        block[4U * i + 3U] = (uint8_t)(words[i] >> 24U);
    }
}

/**
 *  @brief One main step: (n1, n2) <- (rot11(T(n1 + x)) xor n2, n1).
 */
static void main_step(const gost_cipher_t *ctx, uint32_t *n1, uint32_t *n2, uint32_t x)
{
    uint32_t s = *n1 + x;
    uint32_t out = ctx->pi[0][s & 0xFFU] | ctx->pi[1][(s >> 8U) & 0xFFU] |
                   ctx->pi[2][(s >> 16U) & 0xFFU] | ctx->pi[3][(s >> 24U) & 0xFFU];
    uint32_t next = rotl32(out, 11) ^ *n2;
    *n2 = *n1;
    *n1 = next;
}

/** @brief Run @p rounds main steps with keys taken in ascending order. */
static void rounds_ascending(const gost_cipher_t *ctx, uint32_t n[2], unsigned rounds)
{
    for (unsigned round = 0; round < rounds; round++) {
        main_step(ctx, &n[0], &n[1], ctx->key[round % GOST_CIPHER_KEY_WORDS]);
    }
}

/** @brief Run @p rounds main steps with keys taken in descending order. */
static void rounds_descending(const gost_cipher_t *ctx, uint32_t n[2], unsigned rounds)
{
    for (unsigned round = 0; round < rounds; round++) {
        unsigned index = (GOST_CIPHER_KEY_WORDS - 1U) - (round % GOST_CIPHER_KEY_WORDS);
        main_step(ctx, &n[0], &n[1], ctx->key[index]);
    }
}

gost_status_t gost_cipher_init(gost_cipher_t *ctx, const uint32_t key[GOST_CIPHER_KEY_WORDS],
                               gost_sbox_id_t sbox)
{
    if (sbox < 0 || sbox >= GOST_SBOX_COUNT) {
        return GOST_ERR_PARAM;
    }
    return gost_cipher_init_sbox(ctx, key, gost_sbox_tables[sbox]);
}

gost_status_t gost_cipher_init_sbox(gost_cipher_t *ctx, const uint32_t key[GOST_CIPHER_KEY_WORDS],
                                    const uint8_t sbox[8][16])
{
    memcpy(ctx->key, key, sizeof(ctx->key));
    for (unsigned i = 0; i < 4; i++) {
        for (unsigned byte = 0; byte < 256; byte++) {
            uint32_t low = sbox[2U * i][byte & 0xFU];
            uint32_t high = (uint32_t)sbox[2U * i + 1U][(byte >> 4U) & 0xFU] << 4U;
            ctx->pi[i][byte] = (low | high) << (8U * i);
        }
    }
    return GOST_OK;
}

/** @brief Apply the 32-Z or 32-R cycle and swap the halves, in place. */
static void block_cycle(const gost_cipher_t *ctx, uint8_t *block, bool decrypt)
{
    uint32_t n[2];
    words_from_block(block, n);
    if (decrypt) {
        rounds_ascending(ctx, n, GOST_CIPHER_KEY_WORDS);
        rounds_descending(ctx, n, 3U * GOST_CIPHER_KEY_WORDS);
    } else {
        rounds_ascending(ctx, n, 3U * GOST_CIPHER_KEY_WORDS);
        rounds_descending(ctx, n, GOST_CIPHER_KEY_WORDS);
    }
    uint32_t swapped[2] = { n[1], n[0] };
    words_to_block(swapped, block);
}

void gost_cipher_block_encrypt(const gost_cipher_t *ctx, uint8_t block[GOST_CIPHER_BLOCK])
{
    block_cycle(ctx, block, false);
}

void gost_cipher_block_decrypt(const gost_cipher_t *ctx, uint8_t block[GOST_CIPHER_BLOCK])
{
    block_cycle(ctx, block, true);
}

gost_status_t gost_cipher_ecb_encrypt(const gost_cipher_t *ctx, uint8_t *data, size_t len)
{
    if ((len % GOST_CIPHER_BLOCK) != 0U) {
        return GOST_ERR_PARAM;
    }
    for (size_t offset = 0; offset < len; offset += GOST_CIPHER_BLOCK) {
        gost_cipher_block_encrypt(ctx, data + offset);
    }
    return GOST_OK;
}

gost_status_t gost_cipher_ecb_decrypt(const gost_cipher_t *ctx, uint8_t *data, size_t len)
{
    if ((len % GOST_CIPHER_BLOCK) != 0U) {
        return GOST_ERR_PARAM;
    }
    for (size_t offset = 0; offset < len; offset += GOST_CIPHER_BLOCK) {
        gost_cipher_block_decrypt(ctx, data + offset);
    }
    return GOST_OK;
}

/**
 *  @brief Stream transform shared by the gamma and CFB modes.
 *
 *  @p feedback selects the chaining rule: with feedback the register is
 *  encrypted and xored with the block (CFB), without it a counter is
 *  advanced and encrypted (gamma).  When decrypting in feedback mode the
 *  chaining register is restored from the input words.
 */
static void stream_transform(const gost_cipher_t *ctx, const uint32_t iv[2], uint8_t *data,
                             size_t len, bool feedback, bool decrypt)
{
    uint32_t counter[2] = { iv[0], iv[1] };
    uint32_t chaining[2] = { iv[0], iv[1] };
    uint8_t gamma[GOST_CIPHER_BLOCK];
    if (!feedback) {
        words_to_block(counter, gamma);
        gost_cipher_block_encrypt(ctx, gamma);
        words_from_block(gamma, counter);
    }
    for (size_t offset = 0; offset < len; offset += GOST_CIPHER_BLOCK) {
        uint8_t block[GOST_CIPHER_BLOCK] = { 0 };
        size_t take = len - offset < GOST_CIPHER_BLOCK ? len - offset : GOST_CIPHER_BLOCK;
        memcpy(block, data + offset, take);
        uint32_t input[2];
        words_from_block(block, input);
        if (feedback) {
            words_to_block(chaining, gamma);
            gost_cipher_block_encrypt(ctx, gamma);
            words_from_block(gamma, chaining);
        } else {
            counter[0] = (counter[0] + GOST_GAMMA_C1) & UINT32_MAX;
            if (counter[1] > UINT32_MAX - GOST_GAMMA_C2) {
                counter[1]++;
            }
            counter[1] = (counter[1] + GOST_GAMMA_C2) & UINT32_MAX;
            words_to_block(counter, gamma);
            gost_cipher_block_encrypt(ctx, gamma);
            words_from_block(gamma, chaining);
        }
        input[0] ^= chaining[0];
        input[1] ^= chaining[1];
        words_to_block(input, block);
        memcpy(data + offset, block, take);
        if (feedback) {
            if (decrypt) {
                /* Restore the ciphertext words as the next chaining value. */
                input[0] ^= chaining[0];
                input[1] ^= chaining[1];
            }
            chaining[0] = input[0];
            chaining[1] = input[1];
        }
    }
}

gost_status_t gost_cipher_gamma(const gost_cipher_t *ctx, const uint32_t iv[2], uint8_t *data,
                                size_t len)
{
    stream_transform(ctx, iv, data, len, false, false);
    return GOST_OK;
}

gost_status_t gost_cipher_cfb_encrypt(const gost_cipher_t *ctx, const uint32_t iv[2], uint8_t *data,
                                      size_t len)
{
    stream_transform(ctx, iv, data, len, true, false);
    return GOST_OK;
}

gost_status_t gost_cipher_cfb_decrypt(const gost_cipher_t *ctx, const uint32_t iv[2], uint8_t *data,
                                      size_t len)
{
    stream_transform(ctx, iv, data, len, true, true);
    return GOST_OK;
}

gost_status_t gost_cipher_mac(const gost_cipher_t *ctx, const uint8_t *data, size_t len,
                              uint8_t tag[GOST_CIPHER_BLOCK])
{
    if ((len % GOST_CIPHER_BLOCK) != 0U) {
        return GOST_ERR_PARAM;
    }
    uint32_t state[2] = { 0, 0 };
    for (size_t offset = 0; offset < len; offset += GOST_CIPHER_BLOCK) {
        uint32_t block[2];
        words_from_block(data + offset, block);
        state[0] ^= block[0];
        state[1] ^= block[1];
        for (unsigned round = 0; round < 2U * GOST_CIPHER_KEY_WORDS; round++) {
            main_step(ctx, &state[0], &state[1], ctx->key[round % GOST_CIPHER_KEY_WORDS]);
        }
    }
    words_to_block(state, tag);
    return GOST_OK;
}


