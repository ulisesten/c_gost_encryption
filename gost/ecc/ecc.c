/** @return The point at infinity (0, 0). */
static gost_ec_point_t point_infinity(void)
{
    gost_ec_point_t p = { .x = gost_u512_zero(), .y = gost_u512_zero() };
    return p;
}

bool gost_ec_point_is_infinity(gost_ec_point_t point)
{
    return gost_u512_is_zero(point.x) && gost_u512_is_zero(point.y);
}

const gost_curve_t *gost_curve(gost_curve_id_t id)
{
    if (id < 0 || id >= GOST_CURVE_COUNT) {
        return NULL;
    }
    return &gost_curves[id];
}

size_t gost_ec_coordinate_size(const gost_curve_t *curve)
{
    return gost_u512_bit_len(curve->p) > 256U ? 64U : 32U;
}

/**
 *  @brief Compute (numerator / denominator) mod p.
 *  @return The quotient, or zero when the denominator is not invertible.
 */
static gost_u512_t field_divide(gost_u512_t numerator, gost_u512_t denominator,
                                const gost_curve_t *curve)
{
    gost_u512_t inverse;
    if (gost_u512_inv_mod(denominator, curve->p, &inverse) != GOST_OK) {
        return gost_u512_zero();
    }
    gost_u512_t quotient;
    if (gost_u512_mul_mod(numerator, inverse, curve->p, &quotient) != GOST_OK) {
        return gost_u512_zero();
    }
    return quotient;
}

/** @brief y3 = lambda * (x1 - x3) - y1, the shared tail of both rules. */
static gost_status_t finish_point(gost_u512_t lambda, gost_u512_t x1, gost_u512_t x3,
                                  gost_u512_t y1, const gost_curve_t *curve, gost_ec_point_t *out)
{
    gost_u512_t y3 = gost_u512_sub_mod(x1, x3, curve->p);
    gost_status_t status = gost_u512_mul_mod(lambda, y3, curve->p, &y3);
    if (status != GOST_OK) {
        return status;
    }
    out->x = x3;
    out->y = gost_u512_sub_mod(y3, y1, curve->p);
    return GOST_OK;
}

gost_status_t gost_ec_point_add(gost_ec_point_t a, gost_ec_point_t b, const gost_curve_t *curve,
                                gost_ec_point_t *out)
{
    if (gost_ec_point_is_infinity(a)) {
        *out = b;
        return GOST_OK;
    }
    if (gost_ec_point_is_infinity(b)) {
        *out = a;
        return GOST_OK;
    }
    if (gost_u512_cmp(a.x, b.x) == 0) {
        gost_u512_t sum_y = gost_u512_add_mod(a.y, b.y, curve->p);
        if (gost_u512_is_zero(sum_y)) {
            *out = point_infinity();
            return GOST_OK;
        }
        return gost_ec_point_double(a, curve, out);
    }
    gost_u512_t dy = gost_u512_sub_mod(b.y, a.y, curve->p);
    gost_u512_t dx = gost_u512_sub_mod(b.x, a.x, curve->p);
    gost_u512_t lambda = field_divide(dy, dx, curve);
    gost_u512_t square;
    gost_status_t status = gost_u512_mul_mod(lambda, lambda, curve->p, &square);
    if (status != GOST_OK) {
        return status;
    }
    gost_u512_t x3 = gost_u512_sub_mod(square, a.x, curve->p);
    x3 = gost_u512_sub_mod(x3, b.x, curve->p);
    return finish_point(lambda, a.x, x3, a.y, curve, out);
}

gost_status_t gost_ec_point_double(gost_ec_point_t a, const gost_curve_t *curve,
                                   gost_ec_point_t *out)
{
    if (gost_ec_point_is_infinity(a)) {
        *out = point_infinity();
        return GOST_OK;
    }
    gost_u512_t square;
    gost_status_t status = gost_u512_mul_mod(a.x, a.x, curve->p, &square);
    if (status != GOST_OK) {
        return status;
    }
    gost_u512_t numerator = gost_u512_add_mod(gost_u512_add_mod(square, square, curve->p), square,
                                              curve->p);
    numerator = gost_u512_add_mod(numerator, curve->a, curve->p);
    gost_u512_t denominator = gost_u512_add_mod(a.y, a.y, curve->p);
    if (gost_u512_is_zero(denominator)) {
        *out = point_infinity();
        return GOST_OK;
    }
    gost_u512_t lambda = field_divide(numerator, denominator, curve);
    gost_u512_t square_lambda;
    status = gost_u512_mul_mod(lambda, lambda, curve->p, &square_lambda);
    if (status != GOST_OK) {
        return status;
    }
    gost_u512_t x3 = gost_u512_sub_mod(square_lambda, a.x, curve->p);
    x3 = gost_u512_sub_mod(x3, a.x, curve->p);
    return finish_point(lambda, a.x, x3, a.y, curve, out);
}

gost_status_t gost_ec_point_mul(gost_u512_t k, gost_ec_point_t point, const gost_curve_t *curve,
                                gost_ec_point_t *out)
{
    gost_ec_point_t result = point_infinity();
    gost_status_t status = GOST_OK;
    unsigned bits = gost_u512_bit_len(k);
    for (unsigned i = 0; i < bits; i++) {
        status = gost_ec_point_double(result, curve, &result);
        if (status != GOST_OK) {
            return status;
        }
        if (gost_u512_bit(k, bits - 1U - i)) {
            status = gost_ec_point_add(result, point, curve, &result);
            if (status != GOST_OK) {
                return status;
            }
        }
    }
    *out = result;
    return GOST_OK;
}


